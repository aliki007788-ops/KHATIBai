def run() -> None:
    with db_session() as db:
        level_id_by_code: dict[str, str] = {}
        for level_data in LEVELS:
            existing = db.query(LearningLevel).filter_by(code=level_data["code"]).first()
            if existing:
                existing.name_fa = level_data["name_fa"]
                existing.description_fa = level_data["description_fa"]
                existing.order_index = level_data["order_index"]
                level_id_by_code[level_data["code"]] = existing.id
            else:
                level = LearningLevel(**level_data)
                db.add(level)
                db.flush()
                level_id_by_code[level_data["code"]] = level.id

        added = updated = 0
        for level_code, scenarios in SCENARIOS_BY_LEVEL_CODE.items():
            level_id = level_id_by_code[level_code]
            for sc_data in scenarios:
                existing = (
                    db.query(IraqiScenario)
                    .filter_by(level_id=level_id, title_fa=sc_data["title_fa"])
                    .first()
                )
                if existing:
                    existing.description_fa = sc_data["description_fa"]
                    existing.key_vocabulary = sc_data["key_vocabulary"]
                    existing.practice_prompt = sc_data["practice_prompt"]
                    existing.category = sc_data["category"]
                    existing.order_index = sc_data["order_index"]
                    existing.active = True
                    updated += 1
                else:
                    db.add(IraqiScenario(level_id=level_id, **sc_data))
                    added += 1
        db.commit()
        total = sum(len(v) for v in SCENARIOS_BY_LEVEL_CODE.values())
        print(f"Learning content ready. catalog={total} added={added} updated={updated}")


if __name__ == "__main__":
    run()
